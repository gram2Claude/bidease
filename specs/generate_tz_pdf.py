from fpdf import FPDF
from fpdf.enums import XPos, YPos

# ── Пути к шрифтам (Windows) ───────────────────────────────────────────────────
FONT_REG = r"C:\Windows\Fonts\arial.ttf"
FONT_BOLD = r"C:\Windows\Fonts\arialbd.ttf"
FONT_ITAL = r"C:\Windows\Fonts\ariali.ttf"
FONT_MONO = r"C:\Windows\Fonts\consola.ttf"

NX = {"new_x": XPos.LMARGIN, "new_y": YPos.NEXT}

API_NAME = "Bidease Reporting"
TARGET_LANG = "PHP"
MODULE_NAME = "bidease"
OUT_FILE = f"TZ_{MODULE_NAME}_{TARGET_LANG}.pdf"


class PDF(FPDF):
    def header(self): pass

    def footer(self):
        self.set_y(-12)
        self.set_font("arial", "", 8)
        self.set_text_color(120, 120, 120)
        self.cell(0, 8, f"Стр. {self.page_no()}", align="C")


def make_pdf() -> PDF:
    p = PDF(unit="mm", format="A4")
    p.set_margins(left=15, top=15, right=15)
    p.set_auto_page_break(auto=True, margin=15)
    p.add_font("arial", "", FONT_REG)
    p.add_font("arial", "B", FONT_BOLD)
    p.add_font("arial", "I", FONT_ITAL)
    p.add_font("mono", "", FONT_MONO)
    p.add_page()
    return p


pdf = make_pdf()


def H1(text: str) -> None:
    pdf.set_font("arial", "B", 16)
    pdf.set_text_color(20, 20, 20)
    pdf.ln(2)
    pdf.multi_cell(0, 8, text, **NX)
    pdf.ln(1)


def H2(text: str) -> None:
    pdf.set_font("arial", "B", 13)
    pdf.set_text_color(30, 30, 90)
    pdf.ln(2)
    pdf.multi_cell(0, 7, text, **NX)
    pdf.ln(1)


def H3(text: str) -> None:
    pdf.set_font("arial", "B", 11)
    pdf.set_text_color(40, 40, 60)
    pdf.ln(1.5)
    pdf.multi_cell(0, 6, text, **NX)


# Выравнивание по левому краю: justify (дефолт multi_cell) растягивает строки
# с длинными «словами» — URL и query-строками — в редкую сетку пробелов.
LEFT = {"align": "L"}


def P(text: str) -> None:
    pdf.set_font("arial", "", 10)
    pdf.set_text_color(30, 30, 30)
    pdf.multi_cell(0, 5, text, **LEFT, **NX)
    pdf.ln(0.5)


def WARN(text: str) -> None:
    """Врезка-предупреждение: жёлтая подложка."""
    pdf.set_font("arial", "", 10)
    pdf.set_text_color(60, 40, 0)
    pdf.set_fill_color(255, 247, 214)
    pdf.multi_cell(0, 5, text, fill=True, **LEFT, **NX)
    pdf.set_text_color(30, 30, 30)
    pdf.ln(0.8)


def BUL(items: list[str]) -> None:
    pdf.set_font("arial", "", 10)
    pdf.set_text_color(30, 30, 30)
    for it in items:
        pdf.cell(5)
        pdf.cell(3, 5, "•")
        pdf.multi_cell(0, 5, it, **LEFT, **NX)
    pdf.ln(0.5)


def CHECK(items: list[str]) -> None:
    pdf.set_font("arial", "", 10)
    pdf.set_text_color(30, 30, 30)
    for it in items:
        pdf.cell(5)
        pdf.cell(4, 5, "[ ]")
        pdf.multi_cell(0, 5, it, **LEFT, **NX)
    pdf.ln(0.5)


def CODE(text: str) -> None:
    pdf.set_font("mono", "", 8)
    pdf.set_text_color(20, 20, 20)
    pdf.set_fill_color(245, 245, 245)
    pdf.multi_cell(0, 4.2, text, fill=True, border=0, **NX)
    pdf.ln(0.5)


def TABLE(headers: list[str], rows: list[list[str]], widths: list[int]) -> None:
    pdf.set_font("arial", "B", 8.5)
    pdf.set_fill_color(220, 225, 240)
    pdf.set_text_color(20, 20, 20)
    for h, w in zip(headers, widths):
        pdf.cell(w, 6, h, border=1, fill=True)
    pdf.ln()
    pdf.set_font("arial", "", 8.5)
    fill = False
    for row in rows:
        max_lines = 1
        for val, w in zip(row, widths):
            lines = pdf.multi_cell(w, 4.5, val, dry_run=True, output="LINES")
            max_lines = max(max_lines, len(lines))
        h = 4.5 * max_lines
        if pdf.get_y() + h > pdf.h - 15:
            pdf.add_page()
        for val, w in zip(row, widths):
            x, y = pdf.get_x(), pdf.get_y()
            pdf.set_fill_color(245, 245, 250)
            pdf.multi_cell(w, 4.5, val, border=1, fill=fill, max_line_height=4.5)
            pdf.set_xy(x + w, y)
        pdf.ln(h)
        fill = not fill
    pdf.ln(1)


